export const messages: Record<Lang, Dict> = { en, es };

export function t(lang: Lang): Dict {
  return messages[lang];
}

export function pick(lang: Lang, enVal: string, esVal: string): string {
  return lang === "es" ? esVal || enVal : enVal;
}

export function splitBody(raw: string, lang: Lang): string {
  const parts = raw.split(/<!--\s*ES\s*-->/i);
  if (parts.length < 2) return raw.trim();
  return (lang === "es" ? parts[1] : parts[0]).trim();
}
